/* One privacy boundary for page views and optional planning metrics. */
(function () {
    'use strict';
    if (window.__hayyizAnalyticsInitialized) return;
    window.__hayyizAnalyticsInitialized = true;
    const stream = 'G-F94Z3H2D3S';
    const pages = new Set(["/", "/about.html", "/blog-1.html", "/blog-10.html", "/blog-11.html", "/blog-12.html", "/blog-13.html", "/blog-14.html", "/blog-15.html", "/blog-16.html", "/blog-2.html", "/blog-3.html", "/blog-4.html", "/blog-5.html", "/blog-6.html", "/blog-7.html", "/blog-8.html", "/blog-9.html", "/blog.html", "/calculator.html", "/contact.html", "/cumulative.html", "/draw.html", "/first-intermediate.html", "/first-secondary.html", "/founder.html", "/game.html", "/gpa.html", "/habits.html", "/index.html", "/intermediate.html", "/notes.html", "/pomodoro.html", "/privacy.html", "/required-score.html", "/second-intermediate.html", "/second-secondary.html", "/secondary.html", "/third-intermediate.html", "/third-secondary.html", "/todo.html", "/university.html", "/weighted.html"]);
    const actions = new Set(['first_plan', 'plan_adopted', 'focus_started', 'focus_completed', 'task_completed', 'time_updated', 'day_reviewed', 'estimate_extended']);
    const initial = new URL(window.location.href);
    const title = document.title || 'حيز'; // Capture the static head title, never a later task/timer title.
    let ready = false;
    function permitted() {
        const url = new URL(window.location.href);
        return ['http:', 'https:'].includes(url.protocol) && pages.has(url.pathname) &&
            !initial.search && !initial.hash && !url.search && !url.hash &&
            !initial.username && !initial.password && !url.username && !url.password &&
            url.origin === initial.origin && url.pathname === initial.pathname &&
            navigator.doNotTrack !== '1' && navigator.globalPrivacyControl !== true;
    }
    function context() {
        let referrer = '';
        try {
            const previous = new URL(document.referrer);
            if (['http:', 'https:'].includes(previous.protocol)) referrer = previous.origin + '/';
        } catch (_) {}
        return { page_location: initial.origin + initial.pathname, page_referrer: referrer, page_title: title };
    }
    function push() { window.dataLayer.push(arguments); }
    window.hayyizSendPlanningEvent = function (name) {
        if (!ready || !actions.has(name) || !permitted()) return false;
        try { if (localStorage.getItem('hayyiz-planning-metrics') !== 'enabled') return false; }
        catch (_) { return false; }
        push('event', 'planning_' + name, Object.assign(context(), { event_category: 'student_planning', send_to: stream }));
        return true;
    };
    // Query strings can contain task titles, IDs, searches or OAuth data. Leave the URL and app flow intact,
    // and do not load Google's SDK in that document, even if the app later removes the parameters.
    if (!permitted()) return;
    window.dataLayer = Array.isArray(window.dataLayer) ? window.dataLayer : [];
    window.gtag = function (command, name) {
        // Callers cannot introduce arbitrary event fields or override the sanitized page context.
        if (command !== 'event' || typeof name !== 'string' || !name.startsWith('planning_')) return false;
        return window.hayyizSendPlanningEvent(name.slice(9));
    };
    function load() {
        if (!permitted()) return;
        const safe = context();
        push('js', new Date());
        push('set', safe); // Defaults also protect events generated by the SDK itself.
        push('config', stream, Object.assign({}, safe, {
            send_page_view: false, allow_google_signals: false, allow_ad_personalization_signals: false
        }));
        push('event', 'page_view', Object.assign({}, safe, { send_to: stream }));
        const tag = document.createElement('script');
        tag.async = true;
        tag.referrerPolicy = 'no-referrer';
        tag.src = 'https://www.googletagmanager.com/gtag/js?id=' + stream;
        tag.onload = function () {
            ready = true;
            if (typeof window.hayyizFlushPlanningEvents === 'function') window.hayyizFlushPlanningEvents();
        };
        document.head.appendChild(tag);
    }
    // Preserve the home page's existing delayed load; other pages keep an asynchronous SDK load.
    if (!['/', '/index.html'].includes(initial.pathname)) load();
    else if (document.readyState === 'complete') setTimeout(load, 800);
    else window.addEventListener('load', () => setTimeout(load, 800), { once: true });
})();
